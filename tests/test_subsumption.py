def parse_cases(lines, expected):
    return [(a, b, expected) for line in lines for a, b in [line.split()]]

true_cases = parse_cases(TRUE_CASES, True)
auto_false_cases = [(b, a, False) for a, b in [(t[0], t[1]) for t in true_cases] if a != b]
SUBSUMPTION_CASES = sorted(set(true_cases + auto_false_cases + parse_cases(FALSE_CASES, False)))


@pytest.mark.parametrize("acc1,acc2,expected", SUBSUMPTION_CASES)
def test_subsumption(glycan_cache, subsumption, acc1, acc2, expected):
    g1 = glycan_cache(acc1)
    g2 = glycan_cache(acc2)
    assert g1 is not None, f"Could not fetch {acc1}"
    assert g2 is not None, f"Could not fetch {acc2}"
    def _timeout(signum, frame):
        raise TimeoutError(f"{acc1} <= {acc2} exceeded 1s time limit")
    signal.signal(signal.SIGALRM, _timeout)
    signal.alarm(1)
    try:
        result = subsumption.leq(g1, g2)
    finally:
        signal.alarm(0)
    assert result == expected, f"{acc1} <= {acc2}: expected {expected}, got {result}"
